def _always(stage):
    return True


def _dispersion():
    # PySCF adds D3(BJ) through pyscf-dispersion (Linux wheels, the worker image). It has no build that runs
    # on Apple-silicon macOS, where tools/molecules/dispersion.py stands in with the dftd3 package.
    if 'D3' not in XC.upper():
        return
    try:
        import pyscf.dispersion.dftd3  # noqa: F401
    except ImportError:
        try:
            from dispersion import ensure_d3
        except ImportError as e:
            raise ImportError('D3(BJ) needs pyscf-dispersion (Linux) or, on an Apple-silicon Mac, the '
                              "repository's tools/molecules on PYTHONPATH (see this file's docstring)") from e
        ensure_d3()


def molecule(atoms, basis, symmetry=True):
    # Phase 6D spec §8: geometry work (the optimisation, the frequency check) runs with symmetry off --
    # PySCF's geomeTRIC engine holds every geometry to the starting point group, so a structure could not
    # leave it. The final SCF keeps symmetry on, for its orbital labels.
    global _log
    mol = gto.M(atom=atoms, unit='Angstrom', basis=basis, charge=CHARGE, spin=SPIN, symmetry=symmetry, verbose=0)
    _log = _log or open(LOG, 'a')     # one log for every molecule built, appended in order
    mol.stdout, mol.verbose = _log, 4
    return mol


def close_log():
    global _log
    if _log:
        _log.close()
    _log = None


def _settings(mf):
    mf.xc = XC
    mf.grids.level = 4
    mf.conv_tol = 1e-10
    return mf


def make_dft(mol):
    # As tools/molecules/optimise.make_dft: RKS for closed shells, ROKS (one orbital set) for open ones.
    _dispersion()
    return _settings(dft.RKS(mol) if mol.spin == 0 else dft.ROKS(mol))


def geometry_dft(mol):
    # The optimisation's and the frequency check's SCF. PySCF 2.8 has no ROKS Hessian, so an open shell
    # whose structure will be checked does its geometry work UKS; its final SCF stays ROKS (make_dft).
    # A job without the check (compute version 1) keeps the ROKS optimisation it was approved under.
    if mol.spin == 0 or not FREQUENCY_CHECK:
        return make_dft(mol)
    _dispersion()
    return _settings(dft.UKS(mol))


def converge(mol, on_stage, title='SCF'):
    rungs = (('DIIS', {}), ('level shift 0.3 Ha', {'level_shift': 0.3}), ('second-order', None))
    dm = None
    for (label, options), cycles in zip(rungs, MAX_CYCLES):
        stage = f'{title} ({label})'
        on_stage(stage, None)
        mf = make_dft(mol)
        if options is None:
            mf = mf.newton()
        else:
            for name, value in options.items():
                setattr(mf, name, value)
        mf.max_cycle = cycles
        mf.callback = lambda env, stage=stage: on_stage(stage, env.get('e_tot'))
        mf.kernel(dm0=dm)
        if mf.converged:
            return mf
        dm = mf.make_rdm1()
    raise SCFNotConverged('SCF did not converge (DIIS, level shift 0.3 Ha, second-order)')


def _frame(m):
    coords = m.atom_coords(unit='Angstrom')
    return [(m.atom_pure_symbol(i), tuple(float(c) for c in coords[i])) for i in range(m.natm)]


def _uks(mf):
    return isinstance(mf, dft.uks.UKS)


def optimise(atoms, on_stage, on_step, may_start=_always, label='optimisation step', first=1):
    from pyscf.geomopt.geometric_solver import kernel as geometric_kernel
    from pyscf.geomopt.geometric_solver import NotConvergedError
    mol = molecule(atoms, OPTIMISE_BASIS, symmetry=False)
    steps, best, spin = [], [None], [None]
    # Each stage '<label> k' runs from the start of step k (SCF + gradient) to its end, when geomeTRIC calls
    # back; it is told that step's SCF cycle count. The last one is geomeTRIC's wrap-up (or a step the budget
    # refused), with no count: calibrate counts the steps by their counts.
    # The time budget (spec §9) is asked when geomeTRIC asks for another gradient -- which it does only while
    # the optimisation has not converged, so a converged geometry is never "stopped by its time limit" (D12,
    # exactly; Task 6 predicted geomeTRIC's convergence test instead) -- whether the time left covers that
    # step and everything after the optimisation. A no ends the run there, with the lowest-energy geometry
    # evaluated so far (geomeTRIC can take, and then reject, a step that raises the energy). may_start is the
    # worker's budget (worker.TimeBudget, from the job's sizing figures); run on its own, input.py says yes.
    scanner = geometry_dft(mol).nuc_grad_method().as_scanner()

    class Budgeted(type(scanner)):
        def __call__(self, geometry, **kwargs):
            if steps and not may_start('step'):
                energy, n, frame, max_gradient = best[0]
                raise TimeLimitReached(frame, max_gradient, n)
            return super().__call__(geometry, **kwargs)
    scanner.__class__ = Budgeted
    on_stage(f'{label} {first}', None)

    def callback(envs):
        frame = _frame(envs['mol'])
        steps.append(frame)
        n = first + len(steps) - 1
        energy, gradients = float(envs['energy']), envs['gradients']
        base = getattr(envs.get('g_scanner'), 'base', None)
        on_stage(f'{label} {n}', energy, getattr(base, 'cycles', None))
        on_step(n, energy, frame)
        if best[0] is None or energy < best[0][0]:
            best[0] = (energy, n, frame, float(numpy.abs(gradients).max()))
        if base is not None and _uks(base):
            spin[0] = float(base.spin_square()[0])
        on_stage(f'{label} {n + 1}', None)

    try:
        converged, mol_eq = geometric_kernel(scanner, maxsteps=MAX_STEPS, callback=callback,
                                             **{f'convergence_{k}': v for k, v in CONVERGENCE.items()})
    except TimeLimitReached as stop:
        out = {'steps': len(steps), 'converged': False, 'stoppedBy': 'time-limit', 'maxGradient': stop.max_gradient,
               'stoppedAt': stop.step}
        return stop.frame, {**out, 'spinSquared': spin[0]} if spin[0] is not None else out
    except NotConvergedError as e:      # geomeTRIC raises this past MAX_STEPS; anything else propagates
        raise OptimisationNotConverged(f'optimisation did not converge in {MAX_STEPS} steps ({e})')
    if not converged:
        raise OptimisationNotConverged(f'optimisation did not converge in {MAX_STEPS} steps')
    out = {'steps': len(steps), 'converged': True}
    return _frame(mol_eq), {**out, 'spinSquared': spin[0]} if spin[0] is not None else out


SYMMETRY_TOLERANCE = 1e-3     # Å: well inside geomeTRIC's own convergence on the displacement (dmax 1.8e-3 Å)


def _operations(x, charges, tol):
    """Every orthogonal map (3 x 3, about the centroid) that carries the nuclei `x` onto nuclei of the same
    element within `tol`, with the permutation it makes; None for a linear molecule. Each is fixed by where
    it sends two non-parallel nuclear positions, a and b, so the candidates are the pairs of nuclei that
    could be their images (same elements, same distances), each tried proper and improper."""
    n = len(x)
    r = numpy.linalg.norm(x, axis=1)
    off = numpy.flatnonzero(r > tol)
    if not len(off):
        return [(numpy.eye(3), numpy.arange(n))]
    count = {c: int((charges == c).sum()) for c in set(charges.tolist())}
    a = min(off, key=lambda i: (count[charges[i]], -r[i]))           # the rarest element, far from the centre
    across = numpy.linalg.norm(numpy.cross(x[a] / r[a], x), axis=1)
    if across.max() < tol:
        return None
    b = min(numpy.flatnonzero(across > 0.5 * across.max()), key=lambda i: (count[charges[i]], -across[i]))

    def frame(u, v):
        e1 = u / numpy.linalg.norm(u)
        e2 = v - (v @ e1) * e1
        e2 /= numpy.linalg.norm(e2)
        return numpy.array([e1, e2, numpy.cross(e1, e2)])
    reference, ab = frame(x[a], x[b]), numpy.linalg.norm(x[a] - x[b])
    same = charges[:, None] == charges[None, :]
    found = {}
    for a2 in numpy.flatnonzero((charges == charges[a]) & (numpy.abs(r - r[a]) < tol)):
        for b2 in numpy.flatnonzero((charges == charges[b]) & (numpy.abs(r - r[b]) < tol)):
            if b2 == a2 or abs(numpy.linalg.norm(x[a2] - x[b2]) - ab) > tol:
                continue
            image = frame(x[a2], x[b2])
            for handed in (1.0, -1.0):
                op = (image * [[1.0], [1.0], [handed]]).T @ reference
                d = numpy.linalg.norm((x @ op.T)[:, None, :] - x[None, :, :], axis=2)
                d[~same] = numpy.inf
                perm = d.argmin(axis=1)
                if d[numpy.arange(n), perm].max() < tol and len(set(perm.tolist())) == n:
                    found[(tuple(perm.tolist()), handed)] = (op, perm)
    return list(found.values())


def symmetrised(atoms, tol=SYMMETRY_TOLERANCE):
    """`atoms` made exactly symmetric under every operation that holds to within `tol` (the average of each
    nucleus's images, the group's own projection), with the group's order and the largest move (Å).
    An optimised geometry is symmetric only to the optimiser's noise (~1e-5 Å), which PySCF's symmetry
    detection, at 1e-5 bohr, half accepts: it can name the group and then fail to build the
    symmetry-adapted basis (IndexError in symm_adapted_basis), or name a lower one. Repeated, since each
    pass's operations are themselves as noisy as the geometry they came from."""
    xyz = numpy.array([c for _, c in atoms], dtype=float)
    charges = numpy.array([gto.charge(s) for s, _ in atoms])
    if len(atoms) < 2:
        return atoms, 1, 0.0
    centre = xyz.mean(axis=0)
    x = xyz - centre
    order = 1
    for _ in range(4):
        ops = _operations(x, charges, tol)
        if ops is None:                                     # linear: onto the line, and through its centre
            _, _, axes = numpy.linalg.svd(x)
            t = x @ axes[0]
            mirror = numpy.abs(t[:, None] + t[None, :])
            mirror[charges[:, None] != charges[None, :]] = numpy.inf
            perm = mirror.argmin(axis=1)
            centred = mirror[numpy.arange(len(t)), perm].max() < tol and len(set(perm.tolist())) == len(t)
            x = numpy.outer((t - t[perm]) / 2 if centred else t, axes[0])
            order = None                                    # an infinite group
            break
        x = sum(x[perm] @ op for op, perm in ops) / len(ops)
        x -= x.mean(axis=0)
        order = len(ops)
    placed = x + centre
    moved = float(numpy.linalg.norm(placed - xyz, axis=1).max())
    return [(s, tuple(float(c) for c in p)) for (s, _), p in zip(atoms, placed)], order, moved


def spin_record(spin, geometry, frequencies):
    """An open shell's mixed treatment (Task 6 review): PySCF 2.8 has no ROKS Hessian, so geometry and
    frequencies run UKS and the properties ROKS. UKS's <S^2> at the last geometry step and at the Hessian's
    reference, against S(S+1); more than 10 % off is spin contamination, and is said."""
    expected = spin / 2 * (spin / 2 + 1)
    seen = [v for v in (geometry, frequencies) if v is not None]
    contaminated = any(abs(v - expected) > 0.1 * expected for v in seen)
    out = {'methods': 'geometry and frequencies: UKS; properties: ROKS', 'expectedS2': expected,
           'geometryS2': geometry, 'frequenciesS2': frequencies, 'contaminated': contaminated}
    if contaminated:
        at = [f'{v:.3f} at {where}' for v, where in ((geometry, 'the last geometry step'),
                                                      (frequencies, 'the frequency check')) if v is not None]
        out['note'] = (f'UKS spin contamination: <S^2> {" and ".join(at)}, against S(S+1) = {expected:.3f} '
                       '(more than 10 % off)')
    return out


def _scf_for_check(mol, stage):
    mf = geometry_dft(mol)
    mf.kernel()
    if not mf.converged:
        retry = geometry_dft(mol)
        retry.level_shift, retry.max_cycle = 0.3, 200
        retry.kernel(dm0=mf.make_rdm1())
        mf = retry
    if not mf.converged:
        raise SCFNotConverged(f'the {stage} SCF did not converge (DIIS, then level shift 0.3 Ha)')
    return mf


def on_axis(atoms):
    """A linear molecule laid exactly along z, and the axes it was laid along (rows: the molecule's own line,
    then two perpendiculars); anything else unchanged, with None. PySCF's harmonic analysis recognises a
    linear rotor only by an exactly zero moment of inertia, which an optimised geometry's numerical noise
    denies it: it would then project out six modes, not five, and lose a vibration. Still needed after
    symmetrised() (Task 7 review M1 asked whether it was): a molecule exactly on a line that is not an axis
    gives a smallest moment of about -1e-17 from rounding, not zero, which PySCF also reads as non-linear."""
    xyz = numpy.array([c for _, c in atoms], dtype=float)
    centre = xyz.mean(axis=0)
    _, spread, axes = numpy.linalg.svd(xyz - centre)
    if len(atoms) < 2 or (len(spread) > 1 and spread[1] > 1e-4):       # Å
        return atoms, None
    along = (xyz - centre) @ axes[0]
    return [(s, (0.0, 0.0, float(t))) for (s, _), t in zip(atoms, along)], axes


def _rounded(values, name):
    # + 0.0: a component that rounds to zero from below would otherwise be written -0.0
    return (numpy.round(numpy.asarray(values, dtype=float), DECIMALS[name]) + 0.0).tolist()


def frequency_check(atoms, on_stage, stage='frequency check'):
    """Harmonic frequencies at the optimisation level (spec §7): PySCF's analytic Hessian (the D3 part by
    finite differences of its gradient), translations and rotations projected out, in the frame of `atoms`.
    Masses are standard atomic weights (PySCF's atom_mass_list(isotope_avg=True), harmonic_analysis's
    default). Each normal mode is Cartesian displacements, not mass-weighted, scaled so that its squared
    length is 1/mu (mu its reduced mass, amu): PySCF's norm_mode. build() symmetrises the geometry first
    (Task 7 review M1), so the frequencies belong to the geometry the final SCF reports, and a near-linear
    one lies exactly on its line; on_axis then lays that line along z for PySCF."""
    from pyscf.hessian import thermo
    on_stage(stage, None)
    placed, axes = on_axis(atoms)
    mol = molecule(placed, OPTIMISE_BASIS, symmetry=False)
    mf = _scf_for_check(mol, stage)
    modes = thermo.harmonic_analysis(mol, mf.Hessian().kernel(), imaginary_freq=False)
    normal = numpy.asarray(modes['norm_mode'])                  # (mode, atom, xyz) in `placed`'s frame
    if axes is not None:
        normal = normal[..., [2, 0, 1]] @ axes                  # z, x, y -> along axes[0], axes[1], axes[2]
    wavenumbers = _rounded(modes['freq_wavenumber'], 'wavenumbers')
    spin = {'spinSquared': float(mf.spin_square()[0])} if _uks(mf) else {}
    return {'atoms': atoms, 'energyHartree': float(mf.e_tot), **spin, 'wavenumbers': wavenumbers,
            'reducedMasses': _rounded(modes['reduced_mass'], 'reducedMasses'),
            'massesAmu': _rounded(mol.atom_mass_list(isotope_avg=True), 'reducedMasses'),
            'normalModes': _rounded(normal, 'normalModes'),
            'imaginary': [v for v in wavenumbers if v < NOISE_WAVENUMBER],
            'noise': [v for v in wavenumbers if NOISE_WAVENUMBER <= v < 0],
            'zeroPointEnergyHartree': 0.5 * sum(v for v in wavenumbers if v > 0) / WAVENUMBERS_PER_HARTREE}


ZPE_AT_SADDLE = ('at a saddle point: the imaginary modes are left out of the sum, so this is not the zero-point '
                 'energy of a minimum')


def summarise(check, displaced_from=None, displaced=True):
    """The check's verdict. `displaced=False`: a saddle point the run had no time to displace from (M2)."""
    n = len(check['imaginary'])
    if n:
        result = 'saddle-point'
        tail = 'not a minimum' if displaced else 'not displaced (time limit)'
        summary = f'saddle point ({n} imaginary frequenc{"y" if n == 1 else "ies"}), {tail}'
    else:
        result = 'minimum' if displaced_from is None else 'minimum-after-displacement'
        summary = 'true minimum (no imaginary frequencies)'
        if displaced_from is not None:
            summary += f', reached by displacing a saddle point ({displaced_from} imaginary) and re-optimising'
    noise = len(check['noise'])
    if noise:
        summary += (f'; {noise} small imaginary value{"" if noise == 1 else "s"} above {NOISE_WAVENUMBER:g} cm-1 '
                    'treated as numerical noise')
    return {'result': result, 'summary': summary, 'imaginaryCount': n, 'imaginaryWavenumbers': check['imaginary'],
            'noiseWavenumbers': check['noise'],
            'lowestWavenumber': min(check['wavenumbers']) if check['wavenumbers'] else None,
            'zeroPointEnergyHartree': check['zeroPointEnergyHartree'],
            **({'zeroPointEnergyNote': ZPE_AT_SADDLE} if n else {})}


def _displaced(atoms, mode, sign):
    mode = numpy.asarray(mode, dtype=float)
    shift = sign * DISPLACEMENT_ANGSTROM * mode / numpy.abs(mode).max()
    return [(s, tuple(float(c + d) for c, d in zip(xyz, shift[i]))) for i, (s, xyz) in enumerate(atoms)]


def _lower(candidates, stage):
    """The candidate of lowest energy. One whose SCF will not converge is passed over (Task 7 review M6): the
    other sign is as good a way off the saddle point, and the job has been paid for. Only when none
    converges does the job fail."""
    best, failure = None, None
    for atoms in candidates:
        try:
            mf = _scf_for_check(molecule(atoms, OPTIMISE_BASIS, symmetry=False), stage)
        except SCFNotConverged as e:
            failure = e
            continue
        if best is None or mf.e_tot < best[0]:
            best = (mf.e_tot, atoms)
    if best is None:
        raise failure
    return best[1]


def trajectory_comment(step, energy):
    """The comment line of a trajectory frame (the worker writes it). After a displacement it also carries the
    displacement and the check that called for it, as JSON after ' check=': a Spot resume from that frame
    starts a new attempt with nothing else to go on, and would otherwise re-optimise, find the minimum and
    report a plain one (preflight D16). jobs.input_template.resumed_check reads it back."""
    text = f'step {step} E={energy:.10f}'
    if _displacement:
        text += ' check=' + json.dumps(_displacement, separators=(',', ':'))
    return text


def _recheck(atoms, info, on_stage, may_start):
    """The check after the one displacement spec §7 allows: a minimum, or a saddle point labelled as one."""
    n = info['displacedFrom']
    # Task 7 review M4: a re-optimisation the time limit stopped is not called "re-optimised".
    if not info['converged']:
        summary = (f'displaced from a saddle point ({n} imaginary); the re-optimisation stopped at its time limit, '
                   'not converged, and was not checked again')
    elif not may_start('frequency check'):
        summary = (f'displaced from a saddle point ({n} imaginary) and re-optimised; not checked again (no time '
                   'was left for the frequency check)')
    else:
        summary = None
    if summary:
        return atoms, {**info, 'frequencyCheck': {'result': 'not-rechecked', 'imaginaryCount': n, 'summary': summary}}
    recheck = frequency_check(atoms, on_stage, stage='frequency check (after displacement)')
    return atoms, {**info, 'frequencyCheck': summarise(recheck, displaced_from=n), 'frequencies': recheck}


def check_structure(atoms, info, on_stage, on_step, may_start):
    """Spec §7: confirm the optimised structure is a minimum. From a saddle point, displace along the most
    negative mode (both signs, the lower kept), re-optimise once and check again."""
    global _displacement
    if _displacement:
        # A resumed attempt (D16) whose earlier attempt had displaced already: its optimisation was the
        # re-optimisation, so only the recheck is left -- never a second displacement.
        return _recheck(atoms, {**info, **_displacement}, on_stage, may_start)
    if not info['converged']:
        return atoms, {**info, 'frequencyCheck': {'result': 'not-run',
                                                  'summary': 'not checked: the optimisation stopped at its time limit'}}
    if not may_start('frequency check'):
        return atoms, {**info, 'frequencyCheck': {'result': 'not-run',
                                                  'summary': 'not checked: no time was left for the frequency check'}}
    if SPIN and (_electrons(atoms) - SPIN) // 2 == 0:
        # PySCF 2.8's UKS Hessian fails on an empty beta set (H2+: "cannot reshape array of size 0"); the
        # optimisation stands, and the job is not failed for a check that cannot run.
        return atoms, {**info, 'frequencyCheck': {
            'result': 'not-run', 'summary': "not checked: PySCF's UKS Hessian cannot treat a molecule with no beta "
                                            'electrons'}}
    check = frequency_check(atoms, on_stage)
    if not check['imaginary']:
        return atoms, {**info, 'frequencyCheck': summarise(check), 'frequencies': check}
    if not may_start('step'):
        # Task 7 review M2: displacing costs two SCFs, a re-optimisation and a recheck; with no time for even
        # a step, the structure is reported as the saddle point it is.
        return atoms, {**info, 'frequencyCheck': summarise(check, displaced=False), 'frequencies': check}
    n = len(check['imaginary'])
    _displacement = {'displacedFrom': n, 'checkHistory': [summarise(check)]}
    on_stage('displacing from a saddle point', None)
    mode = check['normalModes'][0]       # harmonic_analysis sorts ascending: the first mode is the most negative
    start = _lower([_displaced(atoms, mode, 1), _displaced(atoms, mode, -1)], 'displacement')
    final, again = optimise(start, on_stage, on_step, may_start, label='re-optimisation step', first=info['steps'] + 1)
    final, symmetry = _symmetrise(final)
    info = {**info, **again, 'steps': info['steps'] + again['steps'], **_displacement, 'finalGeometry': symmetry}
    final, info = _recheck(final, info, on_stage, may_start)
    if info['frequencyCheck']['result'] == 'not-rechecked':
        info['frequencies'] = check      # the analysis that found the saddle point: the only one this run has
    return final, info


def _electrons(atoms):
    return sum(gto.charge(s) for s, _ in atoms) - CHARGE


def _symmetrise(atoms):
    # An optimised geometry carries the optimiser's noise; the final SCF's symmetry needs it gone, and so does
    # the frequency check (Task 7 review M1), which must analyse the geometry the final SCF reports.
    placed, order, moved = symmetrised(atoms)
    return placed, {'symmetrised': True, 'groupOrder': order, 'maxDisplacementAngstrom': moved}


