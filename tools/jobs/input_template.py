def _description(job: dict, frequency_check: bool) -> str:
    xc = job['method']['xc']
    if job['recipe'] == 'single':
        return f'one {xc} SCF at the given geometry'
    check = ', a frequency check that confirms a minimum' if frequency_check else ''
    return f'{xc} geomeTRIC optimisation in OPTIMISE_BASIS (symmetry off){check}, then one SCF in BASIS'


def predicted_frequencies_bytes(atom_count: int) -> int:
    """An upper estimate of frequencies.json's size (preflight D10): 3N-5 modes at most (a linear molecule),
    each N x 3 components, a wavenumber and a reduced mass, plus the geometry's 3N coordinates and the N
    masses. About 0.24 MB
    at 50 atoms and 0.9 MB at 100: the 3 MB result budget and the quote's storage must count it."""
    modes = max(3 * atom_count - 5, 0)
    numbers = modes * (3 * atom_count + 2) + 4 * atom_count          # + the geometry and the masses
    return FREQUENCIES_FIXED_BYTES + FREQUENCIES_BYTES_PER_NUMBER * numbers


CHECK_MARKER = ' check='


def resumed_check(comment: str):
    """The displacement a trajectory frame's comment records (input.py's trajectory_comment), to pass to
    render_input when an attempt resumes from that frame (preflight D16); None when the frame came before
    any displacement, or the record is unreadable -- the resumed attempt then optimises and checks afresh,
    which can only repeat a displacement, never hide one."""
    if CHECK_MARKER not in comment:
        return None
    try:
        record = json.loads(comment.split(CHECK_MARKER, 1)[1])
    except ValueError:
        return None
    if not (isinstance(record, dict) and isinstance(record.get('displacedFrom'), int)
            and record['displacedFrom'] >= 1 and isinstance(record.get('checkHistory'), list)):
        return None
    return {'displacedFrom': record['displacedFrom'], 'checkHistory': record['checkHistory']}


def render_input(job: dict, key: str, start=None, resumed_from: int | None = None, resumed_check=None) -> str:
    """`start` replaces the submitted geometry (a resumed optimisation, M4);
    `resumed_from` names the attempt it came from, so the script that ran
    says where its ATOMS came from rather than passing them off as the
    submitted molecule. `resumed_check` (resumed_check() of that frame's
    comment) says the earlier attempt had already displaced off a saddle
    point, so this one re-optimises and rechecks and reports the
    displacement (preflight D16)."""
    mol, method = job['molecule'], job['method']
    atoms = start or [(SYMBOLS[a[0] - 1], (a[1], a[2], a[3])) for a in mol['atoms']]
    resumed = ''
    if start and resumed_from is not None:
        resumed = f"# Resumed from attempt {resumed_from}'s last trajectory frame, not the submitted geometry.\n"
    carried = resumed_check if start else None
    if carried:
        resumed += (f"# That frame came after displacing from a saddle point ({carried['displacedFrom']} imaginary): "
                    'this run re-optimises and rechecks, and does not displace again.\n')
    # Phase 6D spec §7: recipe B checks its structure from compute version 2. A version-1 job (the owner's
    # retry of one) keeps the recipe it was approved and priced under.
    frequency_check = job['recipe'] == 'optimise' and job.get('computeVersion', 1) >= 2
    return Template(TEMPLATE).substitute(
        key=key, recipe=job['recipe'], description=_description(job, frequency_check), resumed=resumed,
        atoms=repr([(s, tuple(float(c) for c in xyz)) for s, xyz in atoms]), charge=mol['charge'],
        spin=mol['multiplicity'] - 1, xc=repr(method['xc']), basis=repr(method['basis']),
        optimise_basis=repr(method['optimiseBasis']), frequency_check=repr(frequency_check),
        resumed_check=repr(carried))
